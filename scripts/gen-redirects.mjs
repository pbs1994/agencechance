// Generates public/.htaccess (OVH / Apache, production) and vercel.json
// (preview deployments) from src/data/redirects.json + src/data/media.json.
// Runs automatically before every build (npm "prebuild").
import fs from 'node:fs';

const redirects = JSON.parse(fs.readFileSync('src/data/redirects.json', 'utf8'));
const media = JSON.parse(fs.readFileSync('src/data/media.json', 'utf8'));
const LANG = '(fr|en|ru)';
const ABS = 'https://agencechance.com';
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/* ---------------- .htaccess ---------------- */
const ht = [];
ht.push(`# GENERATED by scripts/gen-redirects.mjs — edit src/data/redirects.json instead.
Options -Indexes -MultiViews
DirectoryIndex index.html
DirectorySlash On
AddDefaultCharset utf-8
ErrorDocument 404 /404.html

AddType video/mp4 .mp4
AddType image/webp .webp
AddType application/manifest+json .webmanifest

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set X-Frame-Options "SAMEORIGIN"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=()"
  <FilesMatch "\\.(webp|jpg|png|mp4|woff2?|ico)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.html$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
</IfModule>
<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/xml application/javascript application/json image/svg+xml
</IfModule>

# Secrets of the contact form never served
<FilesMatch "^(config\\.php|.*\\.log)$">
  Require all denied
</FilesMatch>

RewriteEngine On
RewriteBase /

# HTTPS + bare domain
RewriteCond %{HTTPS} !=on
RewriteCond %{HTTP:X-Forwarded-Proto} !=https
RewriteRule ^ https://agencechance.com%{REQUEST_URI} [R=301,L]
RewriteCond %{HTTP_HOST} ^www\\.agencechance\\.com$ [NC]
RewriteRule ^ https://agencechance.com%{REQUEST_URI} [R=301,L]

# Former WordPress endpoints: gone for good
RewriteRule ^(wp-admin|wp-includes|wp-json|wp-content/(plugins|themes|cache))(/.*)?$ - [G,L]
RewriteRule ^(wp-login|xmlrpc|wp-cron|wp-signup)\\.php$ - [G,L]

# Root -> French home
RewriteRule ^$ ${ABS}/fr/ [R=301,L]

# WordPress archives that no longer exist
RewriteRule ^${LANG}/blog/\\d{4}(/\\d{2}(/\\d{2})?)?/?$ ${ABS}/$1/blog/ [R=301,L]
RewriteRule ^${LANG}/blog/page/\\d+/?$ ${ABS}/$1/blog/ [R=301,L]
RewriteRule ^(${LANG}/)?(comments/)?feed/?$ ${ABS}/fr/blog/ [R=301,L]
RewriteRule ^${LANG}/(info|information)(/page/\\d+)?/?$ ${ABS}/$1/blog/ [R=301,L]

# Directories without trailing slash: add it (absolute https, one hop)
RewriteCond %{REQUEST_FILENAME} -d
RewriteCond %{REQUEST_URI} !/$
RewriteRule ^(.+)$ ${ABS}/$1/ [R=301,L]

# Legacy pages (one hop each)`);
for (const [from, to] of Object.entries(redirects)) {
  ht.push(`RewriteRule ^${esc(from.replace(/^\//, '').replace(/\/$/, ''))}/?$ ${ABS}${to} [R=301,L]`);
}
ht.push('\n# Legacy WordPress uploads -> optimised images (all WP size variants)');
for (const [url, m] of Object.entries(media)) {
  const rel = decodeURIComponent(url.split('/wp-content/uploads/')[1]);
  const ext = rel.match(/\.(\w+)$/)[1];
  const stem = rel.slice(0, -ext.length - 1).replace(/(-scaled|-e\d{9,})+$/, '');
  const target = `/media/${m.base}-${m.widths.at(-1)}.webp`;
  ht.push(`RewriteRule ^wp-content/uploads/${esc(stem)}(-scaled|-e\\d+|-\\d+x\\d+)*\\.${ext}$ ${ABS}${target} [R=301,L,NC]`);
}
fs.writeFileSync('public/.htaccess', ht.join('\n') + '\n');

/* ---------------- vercel.json (previews) ---------------- */
const vr = [
  { source: '/', destination: '/fr/', permanent: true },
  { source: '/:lang(fr|en|ru)/blog/:y(\\d{4})/:rest*', destination: '/:lang/blog/', permanent: true },
  { source: '/:lang(fr|en|ru)/blog/page/:n', destination: '/:lang/blog/', permanent: true },
  ...Object.entries(redirects).map(([from, to]) => ({ source: from.replace(/\/$/, ''), destination: to, permanent: true })),
];
const vercel = {
  $schema: 'https://openapi.vercel.sh/vercel.json',
  trailingSlash: true,
  redirects: vr,
  headers: [
    { source: '/media/(.*)', headers: [{ key: 'Cache-Control', value: 'public, max-age=31536000, immutable' }] },
    { source: '/video/(.*)', headers: [{ key: 'Cache-Control', value: 'public, max-age=31536000, immutable' }] },
    {
      source: '/(.*)',
      headers: [
        { key: 'X-Content-Type-Options', value: 'nosniff' },
        { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
        // previews must never be indexed
        { key: 'X-Robots-Tag', value: 'noindex' },
      ],
    },
  ],
};
fs.writeFileSync('vercel.json', JSON.stringify(vercel, null, 2) + '\n');
console.log(`.htaccess: ${Object.keys(redirects).length} page + ${Object.keys(media).length} media redirects; vercel.json: ${vr.length} redirects`);
